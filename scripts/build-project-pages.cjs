const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const base = "https://helia33.github.io/Portfolio-Lizza-Tivadze/";
const ids = ["wool-cups", "tklapi-lamp", "zin", "closet-memories", "future-traces", "bugsphere"];
const context = { window: {} };
for (const name of ["works", "mapping-photos", "tklapi-photos", "wool-cups-photos", "future-traces-photos", "bugsphere-photos", "stories"]) {
    vm.runInNewContext(fs.readFileSync(path.join(root, "assets", "data", `${name}.js`), "utf8"), context, { filename: name });
}
const { STORIES, WORKS, MAPPING_PHOTOS, TKLAPI_PHOTOS, WOOL_CUPS_PHOTOS, FUTURE_TRACES_PHOTOS, BUGSPHERE_PHOTOS } = context.window;
const photoSets = {
    "closet-memories": MAPPING_PHOTOS,
    "tklapi-lamp": TKLAPI_PHOTOS,
    "wool-cups": WOOL_CUPS_PHOTOS,
    "future-traces": FUTURE_TRACES_PHOTOS,
    bugsphere: BUGSPHERE_PHOTOS
};
const escape = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const url = (relative) => new URL(relative, base).href;
function photo(id, ref) {
    const named = photoSets[id] && photoSets[id][ref];
    if (named) return named;
    const [page, index] = ref.split("-").map(Number);
    const cut = WORKS[id] && WORKS[id][page - 1] && WORKS[id][page - 1].cuts[index - 1];
    if (!cut) throw new Error(`Missing photo ${id}: ${ref}`);
    return { src: cut.src, alt: cut.desc, w: cut.w, h: cut.h };
}
function image(id, ref, eager = false) {
    const item = photo(id, ref);
    if (!item.alt) throw new Error(`Missing alt text ${id}: ${ref}`);
    const dimensions = item.w && item.h ? ` width="${item.w}" height="${item.h}"` : "";
    return `<figure class="shot"><img src="${escape(item.src)}" alt="${escape(item.alt)}"${dimensions} loading="${eager ? "eager" : "lazy"}" decoding="async"></figure>`;
}
function blockHtml(id, block) {
    const parts = [];
    if (block.heading) parts.push(`<h2 class="story-heading">${escape(block.heading)}</h2>`);
    if (block.label) parts.push(`<p class="story-label">${escape(block.label)}</p>`);
    if (block.text) parts.push(block.type === "quote" ? `<blockquote class="story-quote"><p>${escape(block.text)}</p></blockquote>` : `<p class="story-text">${escape(block.text)}</p>`);
    if (block.image) parts.push(image(id, block.image));
    if (block.images) parts.push(`<div class="story-row">${block.images.map((ref) => image(id, ref)).join("")}</div>`);
    if (block.categories) {
        for (const category of block.categories) parts.push(`<h2 class="story-heading">${escape(category.label)}</h2><div class="story-row">${category.images.map((ref) => image(id, ref)).join("")}</div>`);
    }
    if (block.groups) {
        for (const [label, items] of block.groups) parts.push(`<h2 class="story-heading">${escape(label)}</h2><p>${items.map(escape).join(", ")}</p>`);
    }
    if (block.steps) {
        for (const [label, text, images] of block.steps) parts.push(`<h2 class="story-heading">${escape(label)}</h2><p>${escape(text)}</p><div class="story-row">${images.map((ref) => image(id, ref)).join("")}</div>`);
    }
    if (block.lines) parts.push(`<p>${block.lines.map(escape).join("<br>")}</p>`);
    if (block.type === "video") parts.push(`<video controls preload="none"${block.poster ? ` poster="${escape(block.poster)}"` : ""} src="${escape(block.src)}"></video>`);
    if (block.type === "book") parts.push(`<p><a href="${escape(block.reader)}">Open the project book</a> · <a href="${escape(block.src)}">Download the PDF</a></p>`);
    if (block.caption) parts.push(`<p class="story-caption">${escape(block.caption)}</p>`);
    return `<section class="story-block story-${escape(block.type)}">${parts.join("\n")}</section>`;
}
function metadata(html, file, title, description, imagePath) {
    const canonical = url(file === "index.html" ? "" : file);
    const entries = [
        `<link rel="canonical" href="${canonical}">`,
        '<link rel="icon" href="assets/images/favicon.svg" type="image/svg+xml">',
        '<meta property="og:type" content="website">',
        `<meta property="og:title" content="${escape(title)}">`,
        `<meta property="og:description" content="${escape(description)}">`,
        `<meta property="og:image" content="${escape(url(imagePath))}">`,
        `<meta property="og:url" content="${canonical}">`,
        '<meta name="twitter:card" content="summary_large_image">',
        `<meta name="twitter:title" content="${escape(title)}">`,
        `<meta name="twitter:description" content="${escape(description)}">`,
        `<meta name="twitter:image" content="${escape(url(imagePath))}">`
    ];
    const managed = `    <!-- Sharing metadata: generated by scripts/build-project-pages.cjs -->\n    ${entries.join("\n    ")}\n    <!-- End sharing metadata -->`;
    html = html.replace(/    <!-- Sharing metadata: generated by scripts\/build-project-pages\.cjs -->[\s\S]*?    <!-- End sharing metadata -->\r?\n/, "");
    return html.replace("</head>", `${managed}\n</head>`);
}

for (const file of ["index.html", "work.html", "about.html", "cv.html", "contact.html", "zin-book.html", "project.html"]) {
    const filename = path.join(root, file);
    let html = fs.readFileSync(filename, "utf8");
    const title = html.match(/<title>(.*?)<\/title>/)[1].replace(/&amp;/g, "&");
    const description = html.match(/<meta name="description" content="([^"]*)">/);
    html = metadata(html, file, title, description ? description[1].replace(/&amp;/g, "&") : title, "assets/images/georgian-landscape.jpg");
    if (file === "work.html") html = html.replace(/project\.html\?id=([a-z-]+)/g, "$1.html");
    fs.writeFileSync(filename, html);
}

let template = fs.readFileSync(path.join(root, "project.html"), "utf8");
template = template.replace(/    <script>\s*const projectId[\s\S]*?    <\/script>\r?\n/, "");
for (const [index, id] of ids.entries()) {
    const story = STORIES[id];
    const cover = photo(id, story.cover);
    const next = ids[(index + 1) % ids.length];
    const facts = story.facts.map(([label, value]) => `<div><dt>${escape(label)}</dt><dd>${escape(value)}</dd></div>`).join("");
    const main = `<main class="story" id="story">
${id === "future-traces" ? "        <!-- TODO(owner): confirm whether the crack appeared after two firings or the icon broke after the third firing. -->\n" : ""}\
        <header class="story-hero">${image(id, story.cover, true)}<div class="hero-words"><p class="hero-meta">${escape(story.number)} — ${escape(story.discipline)} · ${escape(story.year)}</p><h1 class="hero-title">${escape(story.title)}</h1><p class="hero-tagline">${escape(story.tagline)}</p></div></header>
        <dl class="story-facts section-wrap">${facts}</dl>
        <div class="story-body">${story.blocks.map((block) => blockHtml(id, block)).join("\n")}</div>
        <a class="story-back section-wrap" href="${next}.html">Next project: ${escape(STORIES[next].title)} →</a>
        <a class="story-back section-wrap" href="work.html">← All work</a>
    </main>`;
    let html = template.replace(/<main class="story" id="story">[\s\S]*?<\/main>/, main);
    html = html.replace('<body class="inner case"', `<body class="inner case project-${id}" data-project="${id}" style="--tone: ${story.tone}"`);
    html = html.replace(/<title>.*?<\/title>/, `<title>${escape(story.title)} — Lizza Tivadze</title>`);
    html = html.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${escape(story.tagline)}">`);
    html = metadata(html, `${id}.html`, `${story.title} — Lizza Tivadze`, story.tagline, cover.src);
    fs.writeFileSync(path.join(root, `${id}.html`), html);
}
console.log(`Generated ${ids.length} project pages and updated sharing metadata.`);
